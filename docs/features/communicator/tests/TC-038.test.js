import test from 'node:test';
import assert from 'node:assert/strict';
import {browserChat,expect} from './browser-chat-fixture.js';

test('TC-038: existing chat loads history, sends a streamed turn and safely recovers a failed reload without replay',{timeout:45000},async t=>{
  const rows=Array.from({length:60},(_,index)=>({id:`history-${index}`,role:index%2?'assistant':'user',content:`Earlier message ${index}`}));
  rows[59].content='## Existing answer\n\n'+('A readable paragraph. '.repeat(100));
  rows[58]={id:'history-58',role:'tool',content:'PRIVATE_TOOL_PAYLOAD',tool_name:'shell'};
  const chat=await browserChat(t,{existing:true,rows,historyFailure:3,viewport:{width:390,height:844}});
  await expect(chat.page.locator('#chat-status')).toContainText('Chat is unavailable');
  await expect(chat.draft).toBeDisabled();assert.equal(chat.turns.length,0);
  assert.equal(chat.requests.filter(row=>row.url.startsWith('/api/sessions/nedcom-main/messages?')).length,3);
  chat.setHistoryFailure(false);await chat.page.locator('#chat-retry').click();await chat.ready();
  await expect(chat.page.locator('#transcript article')).toHaveCount(49);
  await expect(chat.page.locator('#transcript h2')).toHaveText('Existing answer');
  await expect(chat.page.locator('#transcript')).not.toContainText('PRIVATE_TOOL_PAYLOAD');
  await chat.page.locator('#transcript').evaluate(node=>node.scrollTo({top:0,behavior:'instant'}));
  await expect(chat.page.locator('#transcript article')).toHaveCount(59);
  await expect(chat.page.locator('#transcript')).toContainText('Earlier message 0');
  await chat.page.locator('#transcript').evaluate(node=>node.scrollTo({top:node.scrollHeight,behavior:'instant'}));
  await chat.draft.fill('Interrupted request');await chat.draft.press('Enter');
  await expect.poll(()=>chat.turns.length).toBe(1);
  chat.turns[0].partial();await expect(chat.page.locator('[data-state="streaming"]')).toContainText('Visible partial 1');
  assert.equal(chat.turns[0].res.writableEnded,false);
  chat.turns[0].interrupt();
  await expect(chat.page.locator('#chat-status')).toContainText('Delivery could not be confirmed');
  await expect(chat.page.locator('#chat-send')).toBeDisabled();await expect(chat.draft).toHaveValue('Interrupted request');
  await chat.draft.press('Enter');assert.equal(chat.turns.length,1);
  await chat.page.locator('#chat-retry').click();await chat.ready();assert.equal(chat.turns.length,1);
  await chat.page.locator('#transcript').evaluate(node=>node.scrollTo({top:node.scrollHeight,behavior:'instant'}));
  await chat.draft.fill('Continue the existing chat');await chat.draft.press('Enter');
  await expect.poll(()=>chat.turns.length).toBe(2);
  chat.turns[1].partial();await expect(chat.page.locator('[data-state="streaming"]')).toContainText('Visible partial 2');
  chat.setHistoryFailure(true);chat.turns[1].finish();
  await expect(chat.page.locator('#chat-status')).toContainText('Delivery could not be confirmed');
  await expect(chat.page.locator('#chat-send')).toBeDisabled();await expect(chat.draft).toHaveValue('Continue the existing chat');
  assert.equal(chat.messages.length,62);assert.equal(chat.turns.length,2);
  chat.setHistoryFailure(false);await chat.page.locator('#chat-retry').click();await chat.ready();
  await expect(chat.draft).toHaveValue('Continue the existing chat');assert.equal(chat.turns.length,2);
  await chat.page.reload();await chat.ready();
  await expect(chat.page.locator('[data-message-id="sent-2"]')).toHaveCount(1);
  await expect(chat.page.locator('[data-message-id="reply-2"] .message-content strong')).toHaveText('Completed reply 2');
  assert.equal(chat.turns.length,2);assert.equal(chat.requests.filter(row=>row.method==='POST'&&row.url==='/api/sessions').length,0);
  assert.deepEqual(chat.errors,[]);
});
