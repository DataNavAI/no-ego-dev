  const home=await mkdtemp(join(tmpdir(),'com-logs-'));t.after(()=>rm(home,{recursive:true,force:true}));
  const signals=new EventEmitter();const output=[];const io={log:x=>output.push(x),error:x=>output.push(x)};
  let ready;const listening=new Promise(resolve=>{ready=resolve;});
  const pending=runCommunicatorCli([],io,{home,signals,env:{NED_HUB_TOKEN:'ned_synthetic_secret_123456789',NED_INSTANCE_NAME:'test'},createServer:()=>({listen:async()=> 'http://127.0.0.1:12345',close:async()=>{}}),startHub:(_config,_url,{onStatus})=>{onStatus('online');ready();return {close:async()=>{}};}});
  await listening;signals.emit('SIGTERM');assert.equal(await pending,0);
