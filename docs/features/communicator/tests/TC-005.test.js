import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,statSync,renameSync,symlinkSync,unlinkSync,existsSync,writeFileSync,mkdirSync,chmodSync} from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fixture} from './fixtures.js';
import {openNedDatabaseReadOnly} from '../../../../src/database.js';
test('TC-005: current registry, readonly persistence and canonical folder isolation',async t=>{
  const f=await fixture(t);const before=f.writer.connection.prepare('SELECT * FROM ned_feature_data').all();
  const tasksBefore=f.writer.connection.prepare('SELECT * FROM ned_work_items').all();
  const folderMode=statSync(f.roots[0]).mode;const sentinelMode=statSync(path.join(f.roots[0],'sentinel')).mode;
  const mode=statSync(f.databasePath).mode;
  const mainBytes=readFileSync(f.databasePath);
  const list=await f.get('/api/projects');assert.equal(list.status,200);
  assert.deepEqual(list.body.projects,[{id:'project-0',name:'shop',displayPath:'~/a/shop'},{id:'project-1',name:'shop',displayPath:'~/b/shop'}]);
  assert.equal((await f.get('/api/capabilities')).body.capabilities.projects,true);
  assert.deepEqual((await f.get('/api/projects/project-0')).body,{project:list.body.projects[0],preview:{status:'unconfigured'}});
  const head=await fetch(f.app.url+'/api/projects',{method:'HEAD'});assert.equal(head.status,200);assert.equal(await head.text(),'');
  const reader=openNedDatabaseReadOnly({databasePath:f.databasePath});
  assert.throws(()=>reader.prepare("DELETE FROM ned_projects").run(),/readonly/);reader.close();assert.deepEqual(readFileSync(f.databasePath),mainBytes);
  const cliRoot=path.join(f.home,'c');mkdirSync(cliRoot);
  execFileSync(process.execPath,['bin/ned.js','task','init','--database',f.databasePath,'--project',cliRoot,'--json'],{timeout:5000});
  const committed=(await f.get('/api/projects')).body.projects;assert.equal(committed.length,3);assert.match(committed.find(row=>row.id!=='project-0' && row.id!=='project-1').id,/^[a-f0-9]{64}$/);
  f.writer.connection.prepare('DELETE FROM ned_projects WHERE id NOT IN (?,?)').run('project-0','project-1');
  f.writer.connection.prepare('DELETE FROM ned_projects WHERE id=?').run('project-1');
  assert.equal((await f.get('/api/projects')).body.projects.length,1);
  assert.equal((await f.get('/api/projects/project-1')).body.error.code,'project_unavailable');
  for(const id of ['unknown','%2Ftmp','%ZZ','..']) assert.equal((await f.get('/api/projects/'+id)).status,404);
  renameSync(f.roots[0],f.roots[0]+'-saved');symlinkSync(f.roots[1],f.roots[0]);
  assert.equal((await f.get('/api/projects/project-0')).body.error.code,'project_folder_unavailable');
  unlinkSync(f.roots[0]);renameSync(f.roots[0]+'-saved',f.roots[0]);
  assert.equal((await f.get('/api/projects/project-0')).status,200);
  renameSync(f.roots[0],f.roots[0]+'-saved');assert.equal((await f.get('/api/projects/project-0')).body.error.code,'project_folder_unavailable');
  writeFileSync(f.roots[0],'not a folder');assert.equal((await f.get('/api/projects/project-0')).body.error.code,'project_folder_unavailable');unlinkSync(f.roots[0]);renameSync(f.roots[0]+'-saved',f.roots[0]);
  assert.equal(readFileSync(path.join(f.roots[0],'sentinel'),'utf8'),'keep');assert.equal(statSync(f.databasePath).mode,mode);
  assert.deepEqual(f.writer.connection.prepare('SELECT * FROM ned_feature_data').all(),before);
  assert.deepEqual(f.writer.connection.prepare('SELECT * FROM ned_work_items').all(),tasksBefore);
  assert.equal(statSync(f.roots[0]).mode,folderMode);assert.equal(statSync(path.join(f.roots[0],'sentinel')).mode,sentinelMode);
  t.diagnostic(`SQLite coordination sidecars observed: WAL=${existsSync(f.databasePath+'-wal')} SHM=${existsSync(f.databasePath+'-shm')}`);
});
test('TC-005: missing/corrupt/unsupported database never initializes and remains recoverable',async t=>{
  const f=await fixture(t);f.writer.connection.prepare('UPDATE ned_schema SET version=2').run();
  assert.deepEqual(await f.get('/api/projects'),{status:503,body:{error:{code:'database_unavailable',message:'Project data could not be loaded.'}}});
  f.writer.connection.prepare('UPDATE ned_schema SET version=1').run();assert.equal((await f.get('/api/projects')).status,200);
  const missing=path.join(f.home,'absent','db.sqlite');assert.throws(()=>openNedDatabaseReadOnly({databasePath:missing}));assert.equal(existsSync(path.dirname(missing)),false);
  chmodSync(f.databasePath,0);assert.equal((await f.get('/api/projects')).body.error.code,'database_unavailable');chmodSync(f.databasePath,0o600);
  f.writer.connection.prepare('DELETE FROM ned_work_items').run();
  f.writer.connection.prepare('DELETE FROM ned_projects').run();assert.deepEqual((await f.get('/api/projects')).body,{projects:[]});
  const corrupt=path.join(f.home,'corrupt.sqlite');writeFileSync(corrupt,'secret corrupt bytes');assert.throws(()=>openNedDatabaseReadOnly({databasePath:corrupt}));assert.equal(readFileSync(corrupt,'utf8'),'secret corrupt bytes');
});
