import test from 'node:test';
import assert from 'node:assert/strict';
import {execFile} from 'node:child_process';
import {mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {promisify} from 'node:util';
import {browserChat,expect} from './browser-chat-fixture.js';

const run=promisify(execFile);

test('TC-043: agent focus switches the project workspace without changing chat', {timeout:45000},async t=>{
  const {home,page,draft,ready,errors}=await browserChat(t);
  const env={...process.env,NED_AGENT_HOME:home};delete env.NED_API_URL;delete env.NED_CORE_URL;
  const command=async (action,project,...flags)=>{
    const {stdout}=await run(process.execPath,['bin/ned.js','task',action,...flags,'--actor','agent:fixture','--project',join(home,project),'--database',join(home,'ned.sqlite'),'--json'],{env});
    return JSON.parse(stdout);
  };
  for(const project of ['Alpha','Beta','Unregistered'])await mkdir(join(home,project));
  for(const project of ['Alpha','Beta'])await command('init',project);
  await ready();
  await expect(page.locator('#left-pane [role=tablist], #app-shell select')).toHaveCount(0);
  await command('focus','Alpha','--request-id','focus-alpha');
  await expect(page.locator('#preview-identity')).toHaveText('Alpha');
  await draft.fill('Keep this draft');
  await page.getByRole('tab',{name:'Preview',exact:true}).click();
  await command('focus','Beta');
  await expect(page.locator('#preview-identity')).toHaveText('Beta');
  await expect(page.getByRole('tab',{name:'Preview',exact:true})).toHaveAttribute('aria-selected','true');
  await command('focus','Alpha','--request-id','focus-alpha');
  await command('create','Alpha','A new task in the other project');
  await assert.rejects(command('focus','Unregistered'));
  await expect(draft).toHaveValue('Keep this draft');
  const evidence=process.env.NED_UI_EVIDENCE_DIR;
  if(evidence)await page.screenshot({path:join(evidence,'chat-first-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  await expect(draft).toBeVisible();
  await expect(page.locator('#preview')).toBeHidden();
  await expect(page.locator('#chat-send')).toBeInViewport({ratio:1});
  if(evidence)await page.screenshot({path:join(evidence,'chat-first-mobile.png')});
  await page.locator('#mobile-project-toggle').click();
  await expect(page.locator('#preview')).toBeVisible();
  await expect(page.locator('#preview-identity')).toHaveText('Beta');
  await expect(page.locator('#mobile-preview-nav')).toHaveAttribute('aria-current','page');
  await page.locator('#navigation-toggle').click();await page.locator('#artifacts-shortcut').click();
  await expect(page.getByRole('heading',{name:'Artifacts',exact:true})).toBeVisible();
  await page.setViewportSize({width:320,height:740});
  await expect(page.locator('#navigation-toggle')).toBeInViewport({ratio:1});await expect(page.locator('#navigation-toggle')).toHaveAttribute('aria-current','page');
  await expect(page.locator('#preview-identity')).toBeVisible();
  assert.equal(await page.evaluate(()=>globalThis.document.documentElement.scrollWidth<=globalThis.innerWidth),true);
  if(evidence)await page.screenshot({path:join(evidence,'chat-first-workspace-mobile.png')});
  if(await page.locator('#preview').isVisible())await page.locator('#context-close').click();
  await expect(draft).toHaveValue('Keep this draft');
  await page.reload();
  await ready();
  await expect(draft).toBeVisible();
  await page.locator('#mobile-project-toggle').click();
  await expect(page.locator('#preview-identity')).toHaveText('Beta');
  assert.deepEqual(errors,[]);
});
